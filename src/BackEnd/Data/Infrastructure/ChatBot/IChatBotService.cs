    // Helper: تجزیه‌ی DataURL امن
    // ============================================================
    private static (byte[] bytes, string mimeType)? TryParseDataUrl(string? dataUrl)
    {
        if (string.IsNullOrWhiteSpace(dataUrl)) return null;
        if (!dataUrl.StartsWith("data:", StringComparison.OrdinalIgnoreCase)) return null;

        var commaIdx = dataUrl.IndexOf(',');
        if (commaIdx < 0) return null;

        var header = dataUrl[..commaIdx]; // data:image/png;base64
        var base64 = dataUrl[(commaIdx + 1)..];

        // MIME type
        var semiIdx = header.IndexOf(';');
        var mime = semiIdx > 5
            ? header[5..semiIdx]
            : header[5..];

        if (string.IsNullOrWhiteSpace(mime)) mime = "image/png";

        try
        {
            var bytes = Convert.FromBase64String(base64);
            return (bytes, mime);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"[ChatBot] base64 decode error: {ex.Message}");
            return null;
        }
    }
    public async Task<string> Ask(List<ChatMessageDto> messages, CancellationToken cancellationToken = default)
    {
        var result = new StringBuilder();

        await foreach (var chunk in AskStreamingAsync(messages, cancellationToken).WithCancellation(cancellationToken))
        {
            if (!string.IsNullOrEmpty(chunk))
            {
                result.Append(chunk);
            }
        }

        return result.ToString();
    }
