    public async IAsyncEnumerable<string> AskStreamingAsync(
        List<ChatMessageDto> messages,
        [EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        var clientOptions = new OpenAIClientOptions { Endpoint = new Uri(url) };
        var client = new ChatClient(_apiModel, new ApiKeyCredential(_apiKey), clientOptions);

        var chatMessages = new List<OpenAI.Chat.ChatMessage>();
        chatMessages.Add(new SystemChatMessage(SystemPrompt));

        foreach (var msg in messages)
        {
            if (msg.IsUser)
            {
                var parts = new List<ChatMessageContentPart>();

                // ---- متن ----
                if (!string.IsNullOrWhiteSpace(msg.Content))
                {
                    parts.Add(ChatMessageContentPart.CreateTextPart(msg.Content));
                }

                // ---- تصاویر ----
                if (msg.Images != null && msg.Images.Count > 0)
                {
                    foreach (var img in msg.Images)
                    {
                        var parsed = TryParseDataUrl(img);
                        if (parsed.HasValue)
                        {
                            try
                            {
                                var binary = BinaryData.FromBytes(parsed.Value.bytes);
                                parts.Add(ChatMessageContentPart.CreateImagePart(
                                    binary, parsed.Value.mimeType));
                            }
                            catch (Exception ex)
                            {
                                Console.WriteLine($"[ChatBot] Image part error: {ex.Message}");
                            }
                        }
                        else if (Uri.TryCreate(img, UriKind.Absolute, out var uri)
                                 && (uri.Scheme == "http" || uri.Scheme == "https"))
                        {
                            try
                            {
                                parts.Add(ChatMessageContentPart.CreateImagePart(uri));
                            }
                            catch (Exception ex)
                            {
                                Console.WriteLine($"[ChatBot] Image URL error: {ex.Message}");
                            }
                        }
                    }
                }

                // ---- صداها: qwen-vl-max از صدا پشتیبانی نمی‌کنه ----
                if (msg.Audios != null && msg.Audios.Count > 0)
                {
                    parts.Add(ChatMessageContentPart.CreateTextPart(
                        $"(کاربر {msg.Audios.Count} پیام صوتی ارسال کرده، اما این مدل از صدا " +
                        $"پشتیبانی نمی‌کنه. لطفاً از کاربر بخواه متن پیامش رو بنویسه.)"));
                }

                // ---- ویدیوها ----
                if (msg.Videos != null && msg.Videos.Count > 0)
                {
                    var videoNames = string.Join("، ", msg.Videos);
                    parts.Add(ChatMessageContentPart.CreateTextPart(
                        $"(کاربر ویدیوهای زیر را ارسال کرده است: {videoNames})"));
                }

                // ---- فایل‌ها ----
                if (msg.Files != null && msg.Files.Count > 0)
                {
                    var fileNames = string.Join("، ", msg.Files);
                    parts.Add(ChatMessageContentPart.CreateTextPart(
                        $"(کاربر فایل‌های زیر را ارسال کرده است: {fileNames})"));
                }

                if (parts.Count == 0)
                {
                    parts.Add(ChatMessageContentPart.CreateTextPart("(پیام خالی)"));
                }

                chatMessages.Add(new UserChatMessage(parts));
            }
            else
            {
                if (!string.IsNullOrWhiteSpace(msg.Content))
                {
                    chatMessages.Add(new AssistantChatMessage(msg.Content));
                }
            }
        }

        var completion = client.CompleteChatStreamingAsync(chatMessages, null, cancellationToken);

        await foreach (var update in completion.WithCancellation(cancellationToken))
        {
            if (update.ContentUpdate == null) continue;
            foreach (var contentPart in update.ContentUpdate)
            {
                if (!string.IsNullOrEmpty(contentPart.Text))
                {
                    yield return contentPart.Text;
                }
            }
        }
    }

